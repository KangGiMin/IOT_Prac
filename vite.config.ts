import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { defineConfig, type Plugin } from 'vite';
import react from '@vitejs/plugin-react';
import tailwindcss from '@tailwindcss/vite';

const projectRoot = fileURLToPath(new URL('.', import.meta.url));

// Keep the editable Vite template separate from the static Live Server entry.
function liveServerEntry(): Plugin {
  return {
    name: 'circuit-lab-live-server-entry',
    configureServer(server) {
      server.middlewares.use((request, _response, next) => {
        const [pathname, query] = (request.url ?? '/').split('?');
        if (pathname === '/' || pathname === '/index.html') {
          request.url = `/app.html${query ? `?${query}` : ''}`;
        }
        next();
      });
    },
    async writeBundle() {
      const html = await readFile(
        resolve(projectRoot, 'dist/app.html'),
        'utf8',
      );
      // Relative URLs also work when Live Server serves a parent directory.
      const liveHtml = html.replaceAll('./assets/', './dist/assets/');
      await writeFile(resolve(projectRoot, 'dist/index.html'), html, 'utf8');
      await writeFile(
        resolve(projectRoot, 'index.html'),
        '<!-- Generated by npm run build. Edit app.html or src/, then rebuild. -->\n' +
          liveHtml,
        'utf8',
      );
      console.log('Live Server entry updated: index.html');
    },
  };
}

export default defineConfig({
  base: './',
  plugins: [react(), tailwindcss(), liveServerEntry()],
  build: { rollupOptions: { input: resolve(projectRoot, 'app.html') } },
});
