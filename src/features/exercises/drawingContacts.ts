export type ContactKind = 'a' | 'b' | 'changeover' | 'unknown';
export interface DrawingPoint {
  x: number;
  y: number;
  role: 'c' | 'a' | 'b' | '?';
}
export interface DrawingContact {
  owner: string;
  kind: ContactKind;
  points: DrawingPoint[];
  note?: string;
}
const pair = (
  owner: string,
  kind: 'a' | 'b',
  x: number,
  top: number,
  bottom: number,
): DrawingContact => ({
  owner,
  kind,
  points: [
    { x, y: top, role: 'c' },
    { x, y: bottom, role: kind },
  ],
});
const a = (owner: string, x: number, top: number, bottom: number) =>
  pair(owner, 'a', x, top, bottom);
const b = (owner: string, x: number, top: number, bottom: number) =>
  pair(owner, 'b', x, top, bottom);
const horizontal = (
  owner: string,
  kind: 'a' | 'b',
  left: number,
  right: number,
  y: number,
): DrawingContact => ({
  owner,
  kind,
  points: [
    { x: left, y, role: 'c' },
    { x: right, y, role: kind },
  ],
});
const change = (
  owner: string,
  cx: number,
  cy: number,
  ax: number,
  ay: number,
  bx: number,
  by: number,
): DrawingContact => ({
  owner,
  kind: 'changeover',
  points: [
    { x: cx, y: cy, role: 'c' },
    { x: ax, y: ay, role: 'a' },
    { x: bx, y: by, role: 'b' },
  ],
});
const unknown = (owner: string, x: number, y: number): DrawingContact => ({
  owner,
  kind: 'unknown',
  points: [{ x, y, role: '?' }],
  note: '원본에 접점 모양이 생략되어 있습니다. a/b를 단정하지 않습니다.',
});
const tilted = (owner: string, cx: number, cy: number, ax: number, ay: number): DrawingContact => ({
  owner,
  kind: 'a',
  points: [
    { x: cx, y: cy, role: 'c' },
    { x: ax, y: ay, role: 'a' },
  ],
});
